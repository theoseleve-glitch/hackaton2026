// Regenerates apps/server/src/content/option-vote-packs.ts from the authored
// wave-2 content packs in content/packs/. Run from the bloop root:
//   node scripts/build-packs.mjs
// Only spicyLevel 0 items ship in the core packs (launch configs are all-ages);
// spicy siblings come later as separate catalog configs (design §recommendations).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'apps', 'server', 'src', 'content', 'option-vote-packs.ts');

function load(gameId) {
  return JSON.parse(readFileSync(join(root, 'content', 'packs', `${gameId}.json`), 'utf8'));
}

function safeItems(pack) {
  return pack.items.filter((i) => (i.spicyLevel ?? 0) === 0);
}

const tp = load('tu-preferes');
const tpItems = safeItems(tp).map((i) => ({ id: i.id, optionA: i.optionA, optionB: i.optionB }));

const gd = load('gauche-ou-droite');
const gdAxis = gd.axis ?? {
  left: { fr: 'De gauche', en: 'Left-coded' },
  right: { fr: 'De droite', en: 'Right-coded' },
};
const gdItems = safeItems(gd).map((i) => ({
  id: i.id,
  optionA: gdAxis.left,
  optionB: gdAxis.right,
  prompt: i.text,
  emoji: i.emoji,
  debateStarter: i.debateStarter,
}));

const banner = `import type { ContentPack } from '@bloop/engine';
import type { OptionVoteContent } from '@bloop/game-option-vote';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/<gameId>.json —
 * do not edit by hand. Same R2 seam as tracer-pack: packs later move to the
 * CONTENT bucket and load through the registry by RoomMeta.contentRef.
 * Items are bilingual; the client picks the locale at render time.
 */
`;

const body = `${banner}
export const TU_PREFERES_PACK: ContentPack<OptionVoteContent> = {
  id: '${tp.gameId}-core',
  version: ${tp.version ?? 1},
  data: { items: ${JSON.stringify(tpItems, null, 2)} },
};

export const GAUCHE_DROITE_PACK: ContentPack<OptionVoteContent> = {
  id: '${gd.gameId}-core',
  version: ${gd.version ?? 1},
  data: { items: ${JSON.stringify(gdItems, null, 2)} },
};
`;

writeFileSync(out, body);
console.log(`option-vote-packs.ts regenerated — tu-preferes: ${tpItems.length} items, gauche-ou-droite: ${gdItems.length} items`);

// pires-potes: designation cards -> the tracer/VOTE module's prompts array.
// Items use `spicy` (0|1|2) per the by-game spec; core pack = spicy 0 only.
const pp = load('pires-potes');
const ppPrompts = pp.items.filter((i) => (i.spicy ?? 0) <= 0).map((i) => i.text);

const ppOut = join(root, 'apps', 'server', 'src', 'content', 'pires-potes-pack.ts');
writeFileSync(ppOut, `import type { ContentPack } from '@bloop/engine';
import type { TracerContent } from '@bloop/game-tracer';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/pires-potes.json —
 * do not edit by hand. Bilingual {fr,en} designation cards; view() passes them
 * through AS-IS and the client picks the locale. Same R2 seam as tracer-pack.
 */
export const PIRES_POTES_PACK: ContentPack<TracerContent> = {
  id: '${pp.gameId}-core',
  version: ${pp.version ?? 1},
  data: { prompts: ${JSON.stringify(ppPrompts, null, 2)} },
};
`);
console.log(`pires-potes-pack.ts regenerated — ${ppPrompts.length} prompts (spicy 0 only)`);

// ---------------------------------------------------------------------------
// input-guess: quizz-culture-ge (closest-number) + cinquante-cinquante
// (crowd-target) -> apps/server/src/content/input-guess-packs.ts
// ---------------------------------------------------------------------------
const qcg = load('quizz-culture-ge');
// Strip authoring-only fields (tags, difficulty, verifiedAt, source); spicy 0 only.
const qcgItems = qcg.items
  .filter((i) => (i.spicy ?? 0) === 0)
  .map((i) => ({
    id: i.id,
    question: i.question,
    answer: i.answer,
    unit: i.unit ?? null,
    format: i.format === 'year' ? 'year' : 'plain',
    scale: i.scale === 'log' ? 'log' : 'linear',
    funFact: i.funFact,
  }));

const cct = load('cinquante-cinquante');
// Core pack = classic tone with EVERY completion spicy 0. Items containing any
// spicy card are dropped whole — filtering single cards would break the
// exactly-cardsPerRound (6) hand the pick-range validator counts on.
const cctItems = cct.items
  .filter((i) => (i.tone ?? 'classic') === 'classic' && i.completions.every((c) => (c.spicy ?? 0) === 0))
  .map((i) => ({
    id: i.id,
    targetYesPct: i.targetYesPct,
    askKind: i.askKind,
    stem: i.stem,
    completions: i.completions.map((c) => ({ id: c.id, text: c.text, crowdYesPct: c.crowdYesPct })),
  }));

const igOut = join(root, 'apps', 'server', 'src', 'content', 'input-guess-packs.ts');
writeFileSync(igOut, `import type { ContentPack } from '@bloop/engine';
import type { InputGuessContent } from '@bloop/game-input-guess';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/<gameId>.json —
 * do not edit by hand. answer / crowdYesPct / funFact are VALUE SECRETS until
 * reveal (they never enter pre-reveal views). Same R2 seam as tracer-pack.
 */
export const QUIZZ_CULTURE_GE_PACK: ContentPack<InputGuessContent> = {
  id: '${qcg.gameId}-core',
  version: ${qcg.version ?? 1},
  data: { items: ${JSON.stringify(qcgItems, null, 2)} },
};

export const CINQUANTE_CINQUANTE_PACK: ContentPack<InputGuessContent> = {
  id: '${cct.gameId}-core',
  version: ${cct.version ?? 1},
  data: { items: ${JSON.stringify(cctItems, null, 2)} },
};
`);
console.log(`input-guess-packs.ts regenerated — quizz-culture-ge: ${qcgItems.length} items, cinquante-cinquante: ${cctItems.length} items`);

// ---------------------------------------------------------------------------
// secret-role: double-jeu (odd-one-out) -> apps/server/src/content/secret-role-pack.ts
// ---------------------------------------------------------------------------
const dj = load('double-jeu');
// Authoring lint enforced at build time: the PUBLIC theme must never contain
// either HIDDEN word (gameplay spoiler + redaction-audit substring collision).
const themeLeaks = (i) =>
  [i.majority.fr, i.majority.en, i.impostor.fr, i.impostor.en]
    .some((w) => i.theme.fr.includes(w) || i.theme.en.includes(w));
const djItems = dj.items
  .filter((i) => (i.spicyLevel ?? 0) === 0 && !themeLeaks(i))
  .map((i) => ({ id: i.id, theme: i.theme, majority: i.majority, impostor: i.impostor }));

const djOut = join(root, 'apps', 'server', 'src', 'content', 'secret-role-pack.ts');
writeFileSync(djOut, `import type { ContentPack } from '@bloop/engine';
import type { SecretRoleContent } from '@bloop/game-secret-role';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/double-jeu.json —
 * do not edit by hand. theme is PUBLIC; majority / impostor are VALUE SECRETS
 * until finalReveal (they never enter a pre-reveal view). Items whose theme
 * contains either word are dropped at build time (theme-leak lint). Same R2
 * seam as tracer-pack.
 */
export const DOUBLE_JEU_PACK: ContentPack<SecretRoleContent> = {
  id: '${dj.gameId}-core',
  version: ${dj.version ?? 1},
  data: { items: ${JSON.stringify(djItems, null, 2)} },
};
`);
console.log(`secret-role-pack.ts regenerated — double-jeu: ${djItems.length} items (spicy 0, no theme leaks)`);

// ---------------------------------------------------------------------------
// truth-dare: truth-or-dare-2 (fun+lover) + truth-or-drink -> truth-dare-packs.ts
// ---------------------------------------------------------------------------
const asChoice = (c) => (c === 'dare' ? 'dare' : 'truth');
const asTier = (t) => (t === 'spicy' ? 'spicy' : t === 'party' ? 'party' : 'soft');

const tod2 = load('truth-or-dare-2');
const tod2Items = tod2.items.map((i) => ({
  id: i.id,
  choice: asChoice(i.choice),
  intensity: asTier(i.intensity),
  text: i.text,
  deck: i.id.startsWith('lov-') ? 'lover' : 'fun',
  ...(i.props === true ? { props: true } : {}),
}));

const totd = load('truth-or-drink');
const totdItems = totd.items.map((i) => ({
  id: i.id,
  choice: asChoice(i.choice),
  intensity: asTier(i.intensity),
  text: i.text,
}));

const tdOut = join(root, 'apps', 'server', 'src', 'content', 'truth-dare-packs.ts');
writeFileSync(tdOut, `import type { ContentPack } from '@bloop/engine';
import type { TruthDareContent } from '@bloop/game-truth-dare';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/<gameId>.json —
 * do not edit by hand. Tier + deck gating is a RUNTIME config gate at init
 * (allowedIntensities + deck), not a build filter. Same R2 seam as tracer-pack.
 */
export const TRUTH_OR_DARE_2_PACK: ContentPack<TruthDareContent> = {
  id: '${tod2.gameId}-core',
  version: ${tod2.version ?? 1},
  data: { items: ${JSON.stringify(tod2Items, null, 2)} },
};

export const TRUTH_OR_DRINK_PACK: ContentPack<TruthDareContent> = {
  id: '${totd.gameId}-core',
  version: ${totd.version ?? 1},
  data: { items: ${JSON.stringify(totdItems, null, 2)} },
};
`);
console.log(`truth-dare-packs.ts regenerated — truth-or-dare-2: ${tod2Items.length} items, truth-or-drink: ${totdItems.length} items`);

// ---------------------------------------------------------------------------
// spotlight-guess: jeu-de-la-note (scale) + devine-la-question (reverse)
// ---------------------------------------------------------------------------
const note = load('jeu-de-la-note');
const noteItems = note.items
  .filter((i) => (i.intensity ?? 'classic') === 'classic')
  .map((i) => ({
    id: i.id,
    kind: i.kind === 'wheel100' ? 'wheel100' : 'scale10',
    prompt: i.prompt,
    low: i.low,
    high: i.high,
  }));

const dlq = load('devine-la-question');
const dlqItems = dlq.items
  .filter((i) => (i.spicy ?? 0) === 0)
  .map((i) => ({
    id: i.id,
    question: i.question,
    answers: i.answers,
    decoys: i.decoys,
    hints: i.hints,
  }));

const sgOut = join(root, 'apps', 'server', 'src', 'content', 'spotlight-guess-packs.ts');
writeFileSync(sgOut, `import type { ContentPack } from '@bloop/engine';
import type { SpotlightGuessContent } from '@bloop/game-spotlight-guess';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/<gameId>.json —
 * do not edit by hand. The scale target is drawn at init from the seeded RNG;
 * question / decoys / hints are VALUE SECRETS until their reveal tier. Same R2
 * seam as tracer-pack.
 */
export const JEU_DE_LA_NOTE_PACK: ContentPack<SpotlightGuessContent> = {
  id: '${note.gameId}-core',
  version: ${note.version ?? 1},
  data: { mode: 'scale', items: ${JSON.stringify(noteItems, null, 2)} },
};

export const DEVINE_LA_QUESTION_PACK: ContentPack<SpotlightGuessContent> = {
  id: '${dlq.gameId}-core',
  version: ${dlq.version ?? 1},
  data: { mode: 'reverse-question', items: ${JSON.stringify(dlqItems, null, 2)} },
};
`);
console.log(`spotlight-guess-packs.ts regenerated — jeu-de-la-note: ${noteItems.length} items, devine-la-question: ${dlqItems.length} items`);

// ---------------------------------------------------------------------------
// jeu-du-theme (LAST_STANDING) -> last-standing-pack.ts
// ---------------------------------------------------------------------------
const jdt = load('jeu-du-theme');
const jdtItems = jdt.items
  .filter((i) => (i.spicy ?? 0) === 0)
  .map((i) => {
    const shared = i.letters.fr.filter((l) => i.letters.en.includes(l));
    return {
      id: i.id,
      theme: i.theme,
      letters: shared.length >= 3 ? shared : i.letters.fr,
      difficulty: i.difficulty === 2 ? 2 : i.difficulty === 3 ? 3 : 1,
    };
  });

const jdtOut = join(root, 'apps', 'server', 'src', 'content', 'last-standing-pack.ts');
writeFileSync(jdtOut, `import type { ContentPack } from '@bloop/engine';
import type { LastStandingContent } from '@bloop/game-last-standing';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/jeu-du-theme.json —
 * do not edit by hand. exampleWords/tags are STRIPPED at build (exampleWords
 * would prime answers). Per-locale letter lists merge to a shared list so the
 * shouted letter is identical on every phone. Same R2 seam as tracer-pack.
 */
export const JEU_DU_THEME_PACK: ContentPack<LastStandingContent> = {
  id: '${jdt.gameId}-core',
  version: ${jdt.version ?? 1},
  data: { items: ${JSON.stringify(jdtItems, null, 2)} },
};
`);
console.log(`last-standing-pack.ts regenerated — jeu-du-theme: ${jdtItems.length} items (spicy 0 only)`);

// ---------------------------------------------------------------------------
