// ---------------------------------------------------------------------------
// night-day: loup-garou -> night-day-pack.ts
// ---------------------------------------------------------------------------
const lg = load('loup-garou');
const LG_V1_ROLES = ['wolf', 'villager', 'seer', 'witch'];
const LG_SLOTS = [
  'night.intro', 'dawn.death', 'dawn.noDeath',
  'lynch.wolf', 'lynch.villager', 'lynch.none',
  'over.village', 'over.wolves',
];
const lgItems = lg.items.flatMap((i) => {
  if (i.type === 'roleCard') {
    return LG_V1_ROLES.includes(i.role)
      ? [{ id: i.id, type: 'roleCard', role: i.role, name: i.name, text: i.text }]
      : [];
  }
  return LG_SLOTS.includes(i.slot)
    ? [{ id: i.id, type: 'narration', slot: i.slot, text: i.text }]
    : [];
});

const lgOut = join(root, 'apps', 'server', 'src', 'content', 'night-day-pack.ts');
writeFileSync(lgOut, `import type { ContentPack } from '@bloop/engine';
import type { NightDayContent } from '@bloop/game-night-day';

/**
 * GENERATED by scripts/build-packs.mjs from content/packs/loup-garou.json —
 * do not edit by hand. Flavor-only pack (role cards + narration variants).
 * v2 roleCards are dropped until their mechanics land. {victim}/{target}
 * tokens are substituted client-side with nicknames. Same R2 seam as tracer-pack.
 */
export const LOUP_GAROU_PACK: ContentPack<NightDayContent> = {
  id: '${lg.gameId}-core',
  version: ${lg.version ?? 1},
  data: { items: ${JSON.stringify(lgItems, null, 2)} },
};
`);
console.log(`night-day-pack.ts regenerated — loup-garou: ${lgItems.length} items (v1 roles + narration)`);
